#!/usr/bin/env python3
"""Rev C, step 2: hand routes (power, motor, eFuse pins, I2C, touch).  Locked copper.
Usage: revC_preroute.py <in board> <out board>"""
import gc
import sys
import pcbnew
gc.disable()
MM = pcbnew.FromMM
b = pcbnew.LoadBoard(sys.argv[1])
LAY = {'F': pcbnew.F_Cu, 'B': pcbnew.B_Cu}

def V(x, y):
    return pcbnew.VECTOR2I(MM(x), MM(y))

def path(net, layer, pts, w=0.2):
    n = b.FindNet(net)
    assert n is not None, net
    for a, c in zip(pts, pts[1:]):
        t = pcbnew.PCB_TRACK(b)
        t.SetStart(V(*a)); t.SetEnd(V(*c)); t.SetWidth(MM(w)); t.SetLayer(LAY[layer]); t.SetNet(n); t.SetLocked(True)
        b.Add(t)

def via(net, x, y, d=0.6, drill=0.3):
    v = pcbnew.PCB_VIA(b)
    v.SetPosition(V(x, y)); v.SetWidth(MM(d)); v.SetDrill(MM(drill)); v.SetNet(b.FindNet(net)); v.SetLocked(True)
    b.Add(v)

# ---------------- PBUS: J1 pin 1 -> vias under J1 body -> B.Cu along the north edge -> eFuse IN
P = '/PBUS_IN'
path(P, 'F', [(168.55, 101.875), (172.2, 101.875)], 0.5)
via(P, 171.3, 101.875, 0.8, 0.4); via(P, 172.2, 101.875, 0.8, 0.4)
path(P, 'B', [(172.2, 101.875), (171.3, 101.875), (171.3, 92.75), (170.8, 92.25), (155.05, 92.25), (154.55, 92.75), (154.55, 96.0)], 0.5)
via(P, 154.55, 95.05, 0.8, 0.4); via(P, 154.55, 96.0, 0.8, 0.4)
path(P, 'F', [(149.6, 95.05), (150.0, 95.05)], 0.3)
path(P, 'F', [(150.0, 95.05), (154.55, 95.05), (154.55, 96.0)], 0.5)
path(P, 'F', [(151.45, 94.51), (151.45, 95.05)], 0.4)      # C17
path(P, 'F', [(152.8, 94.675), (152.8, 95.05)], 0.5)       # C18
path(P, 'F', [(151.0, 95.05), (151.0, 95.94)], 0.3)        # R13
path(P, 'F', [(152.3, 95.05), (152.3, 95.94)], 0.3)        # R11

# ---------------- eFuse OUT -> VM_P (In2) + C1
M = 'VM_P'
path(M, 'F', [(147.2, 94.55), (146.9, 94.55)], 0.3)
path(M, 'F', [(146.9, 94.55), (144.05, 94.55)], 0.5)
for x, y in ((146.3, 95.35), (145.5, 95.35), (144.7, 95.75)):
    path(M, 'F', [(x, 94.55), (x, y)], 0.4)
    via(M, x, y)

# ---------------- eFuse small pins
path('/EF_ILM', 'F', [(148.175, 93.9), (148.175, 92.75)], 0.2)                   # R15 right at ILM
path('/EF_ILM', 'F', [(148.175, 92.75), (147.21, 92.6)], 0.2)                    # R16
path('GND', 'F', [(148.625, 93.9), (148.625, 93.35), (149.0, 92.98)], 0.2)        # U4 GND -> R15 pad 2
path('GND', 'F', [(149.195, 92.75), (149.6, 92.49), (150.42, 92.49), (151.25, 92.4)], 0.25)
via('GND', 151.25, 92.4)
path('GND', 'F', [(151.45, 93.49), (151.25, 92.4)], 0.25)               # C17 GND
path('/EF_DVDT', 'F', [(149.425, 94.075), (149.9, 94.075), (150.42, 93.555)], 0.2)
path('/EF_ITIMER', 'F', [(147.375, 94.075), (147.05, 93.75), (146.41, 93.7)], 0.2)

# ---------------- motor driver U3: VM, outputs
path(M, 'F', [(78.05, 99.25), (77.9, 99.25), (77.9, 98.6), (78.3, 98.3)], 0.3)
path(M, 'F', [(77.9, 98.6), (77.6, 98.3), (77.11, 98.3)], 0.3)
via(M, 78.3, 98.3)
path(M, 'F', [(77.11, 98.3), (77.6, 97.5)], 0.4)
via(M, 77.6, 97.5)
path('/MOTOR_N', 'F', [(78.05, 99.75), (77.45, 99.75)], 0.25)
path('/MOTOR_N', 'F', [(77.45, 99.75), (77.2, 99.5)], 0.3)
path('/MOTOR_N', 'F', [(77.2, 99.5), (74.0, 99.5), (70.45, 95.95)], 0.5)
path('/MOTOR_P', 'F', [(78.05, 100.25), (77.45, 100.25)], 0.25)
path('/MOTOR_P', 'F', [(77.45, 100.25), (77.2, 100.5)], 0.3)
path('/MOTOR_P', 'F', [(77.2, 100.5), (74.0, 100.5), (70.45, 104.05)], 0.5)
path('GND', 'F', [(78.05, 100.75), (78.7, 100.75)], 0.25)                       # pin 4 -> EP
via('GND', 79.0, 99.6, 0.5, 0.3); via('GND', 79.0, 100.4, 0.5, 0.3)          # EP thermal vias

# ---------------- I2C: J1 -> 0R/ESD south of J1 -> south edge -> U1 (>= 1.85 mm from touch pad T)
path('/J1_SDA', 'F', [(168.55, 99.375), (166.85, 99.375), (166.85, 105.29), (167.9, 105.29), (168.05, 105.44)], 0.2)
path('GND', 'F', [(168.75, 105.6), (169.45, 105.6)], 0.25); via('GND', 169.45, 105.6)   # D5 GND
path('/I2C_SDA', 'F', [(166.85, 106.31), (166.2, 106.99)], 0.2)
via('/I2C_SDA', 166.2, 106.99)
path('/I2C_SDA', 'B', [(166.2, 106.99), (165.44, 107.75), (141.6, 107.75), (141.1, 107.25), (141.1, 104.6)], 0.2)
via('/I2C_SDA', 141.1, 104.6)
path('/I2C_SDA', 'F', [(141.1, 104.6), (140.36, 103.86), (140.36, 102.925)], 0.2)
path('/J1_SCL', 'F', [(168.55, 100.625), (170.1, 100.625)], 0.2)
via('/J1_SCL', 170.1, 100.625)
path('/J1_SCL', 'B', [(170.1, 100.625), (170.1, 106.25), (169.6, 106.75), (168.6, 106.75)], 0.2)
via('/J1_SCL', 168.6, 106.75)
path('/J1_SCL', 'F', [(168.6, 106.75), (168.6, 107.75)], 0.2)
path('/J1_SCL', 'F', [(168.11, 107.75), (169.1, 107.75)], 0.2)
path('GND', 'F', [(169.8, 107.75), (170.6, 107.75)], 0.25); via('GND', 170.6, 107.75)    # D4 GND
path('/I2C_SCL', 'F', [(167.09, 107.75), (135.19, 107.75), (134.64, 107.2), (134.64, 102.925)], 0.2)

# ---------------- touch: T pad -> D2 / R5 (F.Cu, I2C stays >= 5 mm away)
path('/TOUCH_ELEC', 'F', [(163.65, 101.875), (149.175, 101.875), (148.6, 101.3)], 0.2)
path('/TOUCH_ELEC', 'F', [(148.6, 101.3), (147.5, 101.3), (147.11, 100.91), (147.11, 100.4)], 0.2)

pcbnew.SaveBoard(sys.argv[2], b)
print('saved', sys.argv[2])
